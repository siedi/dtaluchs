// Checks the import order of frontend/src and frontend/scripts (CONVENTIONS.md §7, "Reihenfolge der Importe"),
// not a unit test:
//   node scripts/import-order.mjs [--fix]
// Groups: packages < "@/" < "../" < "./", inside a group by code point of the path. A side-effect import
// (`import "x"`) stays where it is and splits the imports into sections; so does any other top-level statement
// between imports. Only inside a section is the order checked and fixed. All top-level import declarations of a file
// count, wherever they stand; re-exports (`export … from`) are not imports and are left alone. src/components/ui/ is
// skipped (generated by shadcn). Prints one line per violation; exit code 1 on any violation, else one "ok" line.
// With --fix each import moves to another slot of its section together with the comments above it and at the end of
// its line; the text between the slots (blank lines) stays where it is.
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"
import { fileURLToPath } from "node:url"
import ts from "typescript"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const SKIP = join(ROOT, "src", "components", "ui")
const FIX = process.argv.includes("--fix")

const files = []
const walk = (dir) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (p === SKIP) continue
    if (e.isDirectory()) walk(p)
    else if (/\.(tsx?|mjs)$/.test(e.name) && !e.name.endsWith(".d.ts")) files.push(p)
  }
}
walk(join(ROOT, "src"))
walk(join(ROOT, "scripts"))
files.sort()

/** Sections of consecutive named imports of a file: arrays of {start, end, path}; the span includes the comments that go with it. */
function sections(file, text) {
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false)
  const out = []
  let cur = []
  for (const st of sf.statements) {
    if (!ts.isImportDeclaration(st) || !st.importClause) {
      if (cur.length) out.push(cur)
      cur = []
      continue
    }
    const lead = ts.getLeadingCommentRanges(text, st.getFullStart()) ?? []
    const trail = ts.getTrailingCommentRanges(text, st.end) ?? []
    cur.push({
      start: lead.length ? lead[0].pos : st.getStart(sf),
      end: trail.length ? trail[trail.length - 1].end : st.end,
      path: st.moduleSpecifier.text,
    })
  }
  if (cur.length) out.push(cur)
  return out
}

const group = (p) => (p.startsWith("@/") ? 1 : p === ".." || p.startsWith("../") ? 2 : p === "." || p.startsWith("./") ? 3 : 0)
const cmp = (a, b) => group(a.path) - group(b.path) || (a.path < b.path ? -1 : a.path > b.path ? 1 : 0)

let bad = 0
for (const file of files) {
  const text = readFileSync(file, "utf8")
  const name = relative(ROOT, file)
  const edits = [] // [start, end, replacement]
  let wrongFile = false
  for (const slots of sections(file, text)) {
    const sorted = [...slots].sort(cmp) // stable: equal paths keep their order
    slots.forEach((s, i) => {
      if (s === sorted[i]) return
      wrongFile = true
      if (!FIX) console.log(`${name}: erwartet \`${sorted[i].path}\` an Stelle ${i + 1}, steht \`${s.path}\``)
      else edits.push([s.start, s.end, text.slice(sorted[i].start, sorted[i].end)])
    })
  }
  if (!wrongFile) continue
  bad++
  if (FIX) {
    let result = ""
    let pos = 0
    for (const [a, b, r] of edits) {
      result += text.slice(pos, a) + r
      pos = b
    }
    writeFileSync(file, result + text.slice(pos))
  }
}

if (FIX) console.log(`${bad} Dateien sortiert, ${files.length} geprüft`)
else if (bad) process.exit(1)
else console.log(`ok: ${files.length} Dateien`)
